// وظيفته الوحيدة: تحقيق شرط "قابل للتثبيت" (installability) اللي يطلبه
// كروم/أندرويد لخاصية "أضف للشاشة الرئيسية" — بدون أي تدخل بأي طلب شبكة.
//
// ⚠️ صفر تخزين مؤقت (Cache) إطلاقاً وبشكل متعمَّد — بعد يوم كامل من مشاكل
// التخزين المؤقت (٢٠٢٦-٠٩-٢٥)، ما نبي نضيف طبقة تعقيد جديدة. كل طلب يمر
// مباشرة للشبكة، تماماً كأن هذا الملف مو موجود من ناحية سلوك الشبكة —
// الفرق الوحيد إنه "مسجَّل"، وهذا كافٍ لشرط المتصفح.
// ============================================================================

self.addEventListener('install', () => {
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(self.clients.claim());
});

// تحديث 2026-10-01: كان كل طلب (حتى طلبات Supabase ورفع الصور بحمولة كبيرة) يمر عبر
// fetch(event.request) بلا معالجة فشل، فأي انقطاع/إلغاء طلب يظهر بالكونسول كخطأ
// «Uncaught (in promise) TypeError: Failed to fetch» من sw.js. الآن: التنقّل بين الصفحات
// فقط يمر هنا (مع التقاط الفشل → استجابة خطأ شبكة نظيفة)، وكل ما عداه يتركه المتصفح
// يتعامل معه مباشرة بدون وسيط. وجود معالج fetch يبقى كافياً لشرط التثبيت.
self.addEventListener('fetch', (event) => {
  if (event.request.mode !== 'navigate') return;
  event.respondWith(fetch(event.request).catch(() => Response.error()));
});
