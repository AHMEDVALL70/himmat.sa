// وظيفته الوحيدة: تحقيق شرط "قابل للتثبيت" (installability) اللي يطلبه
// كروم/أندرويد لخاصية "أضف للشاشة الرئيسية" — بدون أي تدخل بأي طلب شبكة.
//
// ⚠️ صفر تخزين مؤقت (Cache) إطلاقاً وبشكل متعمَّد — بعد يوم كامل من مشاكل
// التخزين المؤقت (٢٠٢٦-٠٩-٢٥)، ما نبي نضيف طبقة تعقيد جديدة. كل طلب يمر
// مباشرة للشبكة، تماماً كأن هذا الملف مو موجود من ناحية سلوك الشبكة —
// الفرق الوحيد إنه "مسجَّل"، وهذا كافٍ لشرط المتصفح.
// ============================================================================

self.addEventListener('install', () => {
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(self.clients.claim());
});

self.addEventListener('fetch', (event) => {
  event.respondWith(fetch(event.request));
});
